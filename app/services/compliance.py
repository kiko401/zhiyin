"""合规词表与红线扫描（D1 / R1–R3）。固定话术与词表依据 PRD 2.8。"""
import re

# R1 硬红线：预测 / 指令 / 承诺
REDLINE_PATTERNS = [
    r"哪(只|些|个).{0,6}(涨停|跌停)",
    r"(明天|下周|后天|未来).{0,8}(涨停|会涨|会跌|能涨|能跌|翻倍|涨到|跌到)",
    r"(能|会|要).{0,4}翻倍",
    r"稳赚|保本|包赚|必涨|必跌|稳涨|稳跌",
    r"帮我(决定|买|卖|选|挑|荐)",
    r"(推荐|挑|选|给)一(只|个|些).{0,4}(股|票|标的)",
    r"(建议|可以)(买入|卖出|清仓|满仓|抄底|逃顶)",
    r"(买入|卖出|清仓)(哪|什么|哪个)",
    r"闭眼(买|入)|无脑(买|入)",
    r"(年底|月底|年底前|几天后?|下月).{0,10}(到|涨到|跌到)\s*\d+",
]

# R2 软风险：情绪化决策语境（不拒绝，强化风险面）
R2_PATTERNS = [
    r"割肉|死扛|扛住|慌.{0,3}死|睡不着|心态.{0,2}崩",
    r"要不要(买|卖|割|补|跑|走)",
    r"补仓|加仓摊|全仓|梭哈|满仓干|抄底|逃顶",
    r"回本就卖|回本.{0,3}走",
    r"上车|下车",
]

BOUNDARY_TEXT = (
    "这个问题涉及涨跌预测或买卖指令，我无法回答。"
    "我可以把它转译为一个研究任务：用真实数据帮你梳理事实、多空论点与风险，决策仍由你来做。"
)

DISCLAIMER = (
    "仅供参考，不构成投资建议；风险提示且不承诺收益；"
    "数据来源与时点见引用；内容由 AI 生成；不作为买卖依据，据此操作风险自担"
)


def scan_redline(text: str) -> bool:
    """D1：命中任一硬红线模式返回 True。"""
    for p in REDLINE_PATTERNS:
        if re.search(p, text):
            return True
    return False


def scan_soft_risk(text: str) -> bool:
    """R2：情绪化决策语境，用于作答时强化风险面。"""
    for p in R2_PATTERNS:
        if re.search(p, text):
            return True
    return False
